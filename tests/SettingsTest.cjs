const assert = require('node:assert/strict');
const settings = require('../web/settings.js');
const store = new Map();
const storage = { getItem: key => store.get(key) || null, setItem: (key, value) => store.set(key, value) };
let value = settings.load(storage).settings;
assert.deepEqual(value, settings.defaults());
value.volume = 0.25; value.muted = true;
settings.bind(value, 0, 0, 'KeyQ');
assert.equal(settings.mask(value.maps[0], new Set(['KeyQ', 'ArrowUp'])), 17);
assert.equal(settings.save(storage, value), true);
assert.deepEqual(settings.load(storage).settings, value);
const swap = settings.bind(value, 0, 0, 'KeyH');
assert.deepEqual(swap, { port: 1, action: 1 });
assert.equal(value.maps[1][1], 'KeyQ');
assert.equal(new Set(value.maps.flat()).size, 16);
assert.throws(() => settings.bind(value, 0, 0, 'Unidentified'));
const bad = settings.defaults(); bad.maps[0][0] = 'Enter';
assert.deepEqual(settings.normalize(bad).maps, settings.DEFAULT_MAPS);
assert.deepEqual(settings.normalize({ version: 2 }), settings.defaults());
assert.equal(settings.normalize({ version: 1, volume: 50 }).volume, 1);
assert.equal(settings.normalize({ version: 1, volume: NaN }).volume, 0.7);
const blocked = { getItem() { throw new Error('blocked'); }, setItem() { throw new Error('blocked'); } };
assert.equal(settings.load(blocked).persistent, false);
assert.equal(settings.save(blocked, value), false);
storage.setItem(settings.STORAGE_KEY, '{');
assert.deepEqual(settings.load(storage).settings, settings.defaults());
assert.equal(settings.label('KeyQ'), 'Q');
assert.equal(settings.mask(value.maps[1], new Set(['KeyQ'])), 2);
console.log('Settings storage, remapping, conflicts, and controller masks passed');
